import assert from 'node:assert/strict';
import { selectDesktopOption, setDesktopCoverTheme } from './desktop-select.mjs';

// test/verify-cover-immersion.mjs — real browser input/timers and deterministic cover fixtures.
export async function verifyCoverImmersion(page, song, output) {
  const previousCoverTheme = await setDesktopCoverTheme(page);
  const emit = (type, data) => page.evaluate(({ type, data }) => window.__foliaEmit(type, data), { type, data });
  const cover = color => `data:image/svg+xml,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"><rect width="100" height="100" fill="${color}"/></svg>`)}`;
  const setSong = async (key, color) => {
    await emit('session', { ...song, key, cover: cover(color) });
    await emit('lyrics', { key, title: song.title, artist: song.artist, content: '[00:01.00]封面主题验证\n[01:30.00]原版歌词动效', source: 'theme-test', cover: '', embedded: false });
    await page.waitForFunction(url => document.querySelector('.track-caption img')?.getAttribute('src') === url, cover(color));
    await page.locator('.waiting-screen').waitFor({ state: 'detached' });
    await page.locator('.cover-theme').waitFor();
  };
  const background = () => page.locator('.desktop-lyrics').evaluate(el => el.style.getPropertyValue('--cover-background'));
  const open = () => page.getByRole('button', { name: '打开歌词设置' }).click();
  const close = () => page.locator('.desktop-topbar [data-settings-trigger]').click();
  await selectDesktopOption(page, '歌词样式', { label: '绘光' });
  await setSong('cover-red', '#dc5432'); const red = await background();
  await page.screenshot({ path: `${output}/cover-theme-red.png` });
  await setSong('cover-blue', '#246edc'); const blue = await background(); assert.notEqual(red, blue);
  await page.screenshot({ path: `${output}/cover-theme-blue.png` });
  await setSong('cover-neutral', '#888888');
  assert.equal(await background(), '#121212');
  await page.screenshot({ path: `${output}/cover-theme-neutral.png` });
  await setSong('cover-red-return', '#dc5432'); assert.equal(await background(), red);
  await open();
  const themeToggle = page.getByRole('checkbox', { name: '主题跟随歌曲封面' });
  await themeToggle.uncheck(); await page.locator('.cover-theme').waitFor({ state: 'detached' });
  await themeToggle.check(); await page.locator('.cover-theme').waitFor();
  await emit('appearance', { acrylic: false, solid: true, highContrast: true });
  await page.locator('.desktop-lyrics.high-contrast').waitFor();
  assert.equal(await page.locator('.desktop-lyrics').evaluate(el => getComputedStyle(el).getPropertyValue('--glass-text')), 'CanvasText');
  await emit('appearance', { acrylic: false, solid: false, highContrast: false });
  // A delayed obsolete cover must never repaint a newer song.
  let releaseCover, coverRequested;
  const gate = new Promise(resolve => { releaseCover = resolve; });
  const requested = new Promise(resolve => { coverRequested = resolve; });
  await page.route('**/delayed-cover.svg', async route => { coverRequested(); await gate; await route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"><rect width="100" height="100" fill="#00cc00"/></svg>' }); });
  await emit('session', { ...song, key: 'slow-cover', cover: new URL('/delayed-cover.svg', page.url()).href });
  await requested;
  await setSong('newer-cover', '#246edc');
  releaseCover(); await page.waitForTimeout(250); assert.equal(await background(), blue);
  await emit('session', { ...song, key: 'newer-cover', cover: '' });
  await page.locator('.cover-theme').waitFor({ state: 'detached' });
  await emit('session', { ...song, key: 'newer-cover', cover: cover('#246edc') });
  await page.locator('.cover-theme').waitFor();
  const automatic = page.getByRole('checkbox', { name: '闲置时自动进入沉浸模式' });
  const hover = page.getByRole('checkbox', { name: '沉浸时移到底部呼出播放控件' });
  const delay = page.getByRole('spinbutton', { name: '无操作等待时间' });
  await automatic.check(); await hover.check();
  await delay.fill('2'); await delay.press('Enter');
  await delay.fill('0'); await delay.press('Enter'); assert.equal(await delay.inputValue(), '2');
  await page.waitForTimeout(2400);
  assert.equal(await page.locator('.immersive').count(), 0, 'settings suspend the idle timer');
  await delay.scrollIntoViewIfNeeded(); await page.screenshot({ path: `${output}/immersion-settings.png` });
  await close(); await page.mouse.move(500, 300); await page.waitForTimeout(1200);
  await page.mouse.move(520, 320); await page.waitForTimeout(1200);
  assert.equal(await page.locator('.immersive').count(), 0, 'mouse activity restarts the configured idle delay');
  await page.locator('.immersive.cursor-idle').waitFor();
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.desktop-statusbar')).visibility === 'hidden');
  assert.equal(await page.locator('.desktop-statusbar').evaluate(el => getComputedStyle(el).visibility), 'hidden');
  assert.equal(await page.locator('.desktop-lyrics').evaluate(el => getComputedStyle(el).cursor), 'none');
  await page.screenshot({ path: `${output}/auto-immersive-idle.png` });
  await page.mouse.move(620, 760); await page.locator('.immersive.controls-revealed').waitFor();
  assert.equal(await page.locator('.cursor-idle').count(), 0);
  await page.getByRole('button', { name: '继续播放音乐', exact: true }).click();
  const command = await page.evaluate(() => window.__foliaCommands.filter(m => m.type === 'mediaControl').at(-1));
  assert.equal(command.value.songKey, 'newer-cover'); assert.equal(command.value.action, 'play');
  await emit('transport', { requestId: command.value.requestId, success: true, message: '测试成功' });
  await page.screenshot({ path: `${output}/immersive-bottom-controls.png` });
  await page.mouse.move(520, 320); await page.locator('.controls-revealed').waitFor({ state: 'detached' });
  await page.keyboard.press('Escape'); await page.locator('.immersive').waitFor({ state: 'detached' });
  await open(); await hover.uncheck(); await automatic.uncheck(); await close();
  await page.getByRole('button', { name: '沉浸显示' }).click(); await page.mouse.move(620, 760);
  assert.equal(await page.locator('.controls-revealed').count(), 0, 'disabled hover keeps the transport hidden');
  await page.locator('.immersive.cursor-idle').waitFor();
  await page.mouse.move(621, 759); await page.locator('.cursor-idle').waitFor({ state: 'detached' });
  await page.keyboard.press('Escape'); await page.locator('.immersive').waitFor({ state: 'detached' });
  await page.waitForTimeout(2300); assert.equal(await page.locator('.immersive').count(), 0, 'automatic immersion can be disabled');
  await open(); await automatic.check(); await hover.check(); await close();
  await page.waitForTimeout(1200); await page.keyboard.press('Shift'); await page.waitForTimeout(1200);
  assert.equal(await page.locator('.immersive').count(), 0, 'keyboard activity restarts the delay');
  await page.locator('.immersive').waitFor(); await page.keyboard.press('Escape'); await open();
  await automatic.uncheck(); await close();
  await setDesktopCoverTheme(page, previousCoverTheme);
  console.log('PASS cover theme / configurable idle immersion / bottom controls checks');
  return ['red-blue cover theme changes', 'neutral palette for monochrome covers', 'stable theme when returning', 'theme switch', 'high contrast preserved', 'stale extraction discarded', 'missing cover fallback', 'native preference commands', 'seconds validation', 'settings suspend timer', 'pointer resets timer', 'idle hides controls and cursor', 'bottom hover reveals working transport', 'leaving bottom hides focused controls', 'hover switch', 'manual immersive cursor hiding', 'mouse restores cursor', 'Escape restores controls', 'automatic switch', 'keyboard resets timer'];
}
